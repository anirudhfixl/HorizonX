/**
 * Data provenance for the Token module.
 *
 * Every value shown to a user comes from exactly one of four sources. Pages and
 * sections label what they show using these kinds, so catalog records, simulated
 * figures, browser-session records and blockchain-verified data are never
 * mistaken for one another.
 *
 * - catalog   Stored HorizonX catalog metadata (name, symbol, description,
 *             recorded contract address, category, status). It has not been
 *             checked against a blockchain.
 * - simulated Illustrative values produced by the application: mock market
 *             figures, simulated management actions, simulated receipts.
 * - session   A record created in this browser session (for example through the
 *             Create Token simulation). It is kept in sessionStorage and is lost
 *             when the session ends.
 * - onchain   Read directly from a blockchain and verified. No on-chain reading
 *             exists in the application yet, so nothing may be labelled this way
 *             today. The kind is defined so the interface is ready for it.
 */

export type DataProvenance = "catalog" | "simulated" | "session" | "onchain";

export interface ProvenanceMeta {
  /** Short label shown in the badge. */
  label: string;
  /** One-sentence explanation shown as a tooltip and read by assistive technology. */
  description: string;
}

export const PROVENANCE_META: Record<DataProvenance, ProvenanceMeta> = {
  catalog: {
    label: "Catalog",
    description:
      "Stored HorizonX catalog record. It has not been verified against a blockchain.",
  },
  simulated: {
    label: "Simulated",
    description:
      "Illustrative value generated by the application. It does not come from a blockchain or a live market feed.",
  },
  session: {
    label: "Session",
    description:
      "Created in this browser session. It is stored temporarily in your browser and is not on a blockchain.",
  },
  onchain: {
    label: "On-chain",
    description: "Read from the blockchain and verified.",
  },
};

