/**
 * Provenance of a token's market figures (price, volume, liquidity, market cap).
 *
 * The application has no live market feed, so market figures are always
 * simulated, whatever the `isLive` flag in the data says. When a real feed is
 * integrated this is the single place to change, and callers will then pass the
 * market record.
 */
export function marketProvenance(): DataProvenance {
  return "simulated";
}

/**
 * Provenance of a token record as a whole.
 *
 * A token whose contract address matches a session receipt is a session record.
 * Every other token comes from the stored catalog. Neither is on-chain.
 */
export function tokenRecordProvenance(
  token: { contractAddress?: string },
  sessionContractAddresses: Iterable<string> = []
): DataProvenance {
  const address = token.contractAddress?.toLowerCase();
  if (!address) return "catalog";
  for (const sessionAddress of sessionContractAddresses) {
    if (sessionAddress.toLowerCase() === address) return "session";
  }
  return "catalog";
}
